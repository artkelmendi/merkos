export const getVehicleBySlug = (slug: string) => {
  const legacySlugs: Record<string, string> = {
    'audi-rs6-avant': 'audi-q5-40-tdi-quattro',
    'mercedes-amg-gt-63-s': 'mercedes-c-220d-4matic',
    'porsche-cayenne-gts': 'audi-q3-35-tdi-s-tronic',
    'range-rover-sport-p530': 'bmw-520d-xdrive-m-sport',
    'volkswagen-golf-r': 'volkswagen-golf-7-2-0-tdi',
  }

  return vehicles.find((vehicle) => vehicle.slug === (legacySlugs[slug] ?? slug))
}
